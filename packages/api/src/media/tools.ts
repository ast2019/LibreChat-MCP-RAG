import { randomUUID } from 'node:crypto';
import { logger } from '@librechat/data-schemas';
import { tool } from '@librechat/agents/langchain/tools';
import { MediaTools, MEDIA_TRANSACTION_CONTEXTS } from 'librechat-data-provider';
import type { TMediaGenerationConfig } from 'librechat-data-provider';
import type { StructuredToolInterface } from '@librechat/agents/langchain/tools';
import type { MediaEndpoint, MediaFetch, MediaUser, SavedMedia } from './types';
import type { MediaBilling, MediaCharge } from './billing';
import type { ServerRequest } from '~/types';
import { generateHiggsfield, generateOpenRouterImage, generateOpenRouterVideo } from './providers';
import { checkMediaAccess, getMediaConfig, resolveMediaEndpoint } from './config';
import { createSpeechProviderClient } from '~/speech/client';
import { pcmToWav } from '~/speech/audio';
import { mediaToolDefinitions } from './definitions';
import { mediaCredits } from './billing';
import { MediaError } from './types';

type TextPart = { type: 'text'; text: string };
type ToolResult = [TextPart[], { content?: unknown[]; file_ids?: string[] }];

export interface MediaToolDeps {
  billing: MediaBilling;
  findBalanceByUser: (userId: string) => Promise<{ packId?: string | null } | null>;
  /** Saves generated bytes as one of the user's files and returns where the client loads it. */
  saveMedia: (
    req: ServerRequest,
    file: { buffer: Buffer; type: string; filename: string; context: string },
  ) => Promise<SavedMedia>;
  /** One of the user's images as bytes, for edits and image-to-video; null when not theirs. */
  loadImage: (
    req: ServerRequest,
    fileId: string,
  ) => Promise<{ buffer: Buffer; type: string } | null>;
  fetch?: MediaFetch;
}

interface RunnableConfig {
  signal?: AbortSignal;
  configurable?: { thread_id?: string };
}

const text = (message: string): ToolResult => [[{ type: 'text', text: message }], {}];

const BUY_HINT = 'they can buy a pack from «خرید اعتبار» (/payment)';

const ERROR_MESSAGES: Record<MediaError['code'], string> = {
  blocked:
    'The provider blocked this request under its content rules. Nothing was charged. Ask the user to rephrase it.',
  timeout:
    'The generation took too long and was stopped. Nothing was charged. Suggest trying again, or a shorter clip.',
  aborted: 'The generation was cancelled. Nothing was charged.',
  provider_error:
    'The generation failed on the provider side. Nothing was charged. Suggest trying again in a moment.',
  no_output: 'The provider returned nothing. Nothing was charged. Suggest trying again.',
  too_large: 'The generated file was too large to keep. Nothing was charged.',
};

function toDataUrl(file: { buffer: Buffer; type: string }): string {
  return `data:${file.type};base64,${file.buffer.toString('base64')}`;
}

function extensionOf(type: string): string {
  const subtype = type.split('/')[1]?.split(/[;+]/)[0] ?? '';
  if (subtype === 'mpeg') {
    return 'mp3';
  }
  if (subtype === 'quicktime') {
    return 'mov';
  }
  return /^[a-z0-9]{2,5}$/.test(subtype) ? subtype : 'bin';
}

function mediaLink(saved: SavedMedia, label: string): string {
  return `[${label}](${saved.filepath})`;
}

/**
 * The in-chat media tools. Each call checks the user's access (an admin switch, or a pack on a
 * paid-only deployment), holds the estimated cost, generates, saves the file for the user, and
 * charges the real cost; a failed generation is never charged.
 */
export function createMediaTools(
  { req, toolNames }: { req: ServerRequest; toolNames: readonly string[] },
  deps: MediaToolDeps,
): StructuredToolInterface[] {
  const doFetch: MediaFetch = deps.fetch ?? ((url, init) => fetch(url, init));
  const speechClient = createSpeechProviderClient({ fetch: doFetch });

  async function guarded(
    pick: (config: TMediaGenerationConfig) => boolean,
    charge: MediaCharge,
    estimateUsd: number,
    priceMultiplier: number,
    work: (config: TMediaGenerationConfig) => Promise<{ result: ToolResult; costUsd?: number }>,
  ): Promise<ToolResult> {
    const config = getMediaConfig(req.config);
    const user = req.user as unknown as MediaUser | undefined;
    if (!config || !pick(config) || !user?.id) {
      return text('This generator is not available on this deployment.');
    }
    const access = await checkMediaAccess(config, user, deps.findBalanceByUser);
    if (!access.ok) {
      return text(
        access.code === 'paid_only'
          ? `Image, video and audio generation are part of paid packs. Tell the user, in their language, that ${BUY_HINT} to unlock them.`
          : 'An admin has turned media generation off for this account. Tell the user, in their language.',
      );
    }
    const estimate = mediaCredits(estimateUsd, priceMultiplier);
    const held = await deps.billing.hold(req, charge, estimate);
    if (held === 'insufficient') {
      return text(
        `The user's credit does not cover this (about $${(estimate / 1e6).toFixed(2)}). Nothing was made or charged. Tell them, in their language, that ${BUY_HINT}.`,
      );
    }
    try {
      const { result, costUsd } = await work(config);
      const credits = costUsd != null ? mediaCredits(costUsd, priceMultiplier) : estimate;
      await deps.billing.record(req, charge, credits);
      return result;
    } catch (error) {
      if (error instanceof MediaError) {
        logger.warn(`[media] ${charge.context} failed: ${error.code}`);
        return text(ERROR_MESSAGES[error.code]);
      }
      logger.error(`[media] ${charge.context} failed`, error);
      return text(ERROR_MESSAGES.provider_error);
    } finally {
      await held?.release();
    }
  }

  const endpointOf = (config: TMediaGenerationConfig): MediaEndpoint => {
    const endpoint = resolveMediaEndpoint(req.config, config);
    if (!endpoint) {
      throw new MediaError('provider_error', 'The media endpoint has no server key');
    }
    return endpoint;
  };

  /** Multiplier of the OpenRouter endpoint, read before the hold so estimate and charge agree. */
  const multiplierOf = (): number => {
    const config = getMediaConfig(req.config);
    return config ? (resolveMediaEndpoint(req.config, config)?.priceMultiplier ?? 1) : 1;
  };

  async function loadReferences(ids: unknown): Promise<string[]> {
    if (!Array.isArray(ids)) {
      return [];
    }
    const references: string[] = [];
    for (const id of ids.slice(0, 4)) {
      if (typeof id !== 'string' || id === '') {
        continue;
      }
      const image = await deps.loadImage(req, id);
      if (image) {
        references.push(toDataUrl(image));
      }
    }
    return references;
  }

  function imageResult(image: { buffer: Buffer; type: string }, note: string): ToolResult {
    const fileId = randomUUID();
    return [
      [
        {
          type: 'text',
          text: `${note} It is already shown to the user; do not list links to it. generated_image_id: "${fileId}"`,
        },
      ],
      {
        content: [{ type: 'image_url', image_url: { url: toDataUrl(image) } }],
        file_ids: [fileId],
      },
    ];
  }

  const builders: Record<MediaTools, () => StructuredToolInterface> = {
    [MediaTools.image]: () =>
      tool(
        async (
          input: { prompt?: string; aspect_ratio?: string; image_ids?: string[] },
          runnable,
        ) => {
          const run = runnable as RunnableConfig | undefined;
          const model = getMediaConfig(req.config)?.image?.model ?? '';
          const multiplier = multiplierOf();
          return guarded(
            (config) => config.image != null,
            {
              model,
              endpoint: getMediaConfig(req.config)?.endpoint ?? '',
              context: MEDIA_TRANSACTION_CONTEXTS.image,
              conversationId: run?.configurable?.thread_id,
            },
            getMediaConfig(req.config)?.image?.estimateUsd ?? 0,
            multiplier,
            async (config) => {
              const image = config.image!;
              const references = await loadReferences(input.image_ids);
              const generated = await generateOpenRouterImage(doFetch, endpointOf(config), {
                model: image.model,
                prompt: String(input.prompt ?? ''),
                aspectRatio: input.aspect_ratio,
                resolution: image.resolution,
                references,
                user: req.user?.id,
                timeoutMs: image.timeoutMs,
                signal: run?.signal,
              });
              return {
                result: imageResult(generated, 'The image was generated.'),
                costUsd: generated.costUsd,
              };
            },
          );
        },
        { ...mediaToolDefinitions[MediaTools.image] } as never,
      ) as unknown as StructuredToolInterface,

    [MediaTools.video]: () =>
      tool(
        async (
          input: {
            prompt?: string;
            duration_seconds?: number;
            aspect_ratio?: string;
            first_frame_image_id?: string;
          },
          runnable,
        ) => {
          const run = runnable as RunnableConfig | undefined;
          const video = getMediaConfig(req.config)?.video;
          const duration = Math.min(
            Math.max(
              Math.round(Number(input.duration_seconds) || (video?.defaultDuration ?? 5)),
              1,
            ),
            video?.maxDuration ?? 8,
          );
          return guarded(
            (config) => config.video != null,
            {
              model: video?.model ?? '',
              endpoint: getMediaConfig(req.config)?.endpoint ?? '',
              context: MEDIA_TRANSACTION_CONTEXTS.video,
              conversationId: run?.configurable?.thread_id,
            },
            duration * (video?.estimateUsdPerSecond ?? 0),
            multiplierOf(),
            async (config) => {
              const settings = config.video!;
              const [firstFrame] = input.first_frame_image_id
                ? await loadReferences([input.first_frame_image_id])
                : [];
              const generated = await generateOpenRouterVideo(doFetch, endpointOf(config), {
                model: settings.model,
                prompt: String(input.prompt ?? ''),
                duration,
                resolution: settings.resolution,
                aspectRatio: input.aspect_ratio,
                generateAudio: settings.generateAudio,
                firstFrame,
                pollIntervalMs: settings.pollIntervalMs,
                timeoutMs: settings.timeoutMs,
                signal: run?.signal,
              });
              const saved = await deps.saveMedia(req, {
                buffer: generated.buffer,
                type: generated.type,
                filename: `video.${extensionOf(generated.type)}`,
                context: MEDIA_TRANSACTION_CONTEXTS.video,
              });
              return {
                result: text(
                  `The ${duration}-second video is ready (file_id: ${saved.file_id}). Put this markdown in your reply exactly as written so it plays in the chat: ${mediaLink(saved, '🎬 video')}`,
                ),
                costUsd: generated.costUsd,
              };
            },
          );
        },
        { ...mediaToolDefinitions[MediaTools.video] } as never,
      ) as unknown as StructuredToolInterface,

    [MediaTools.speech]: () =>
      tool(
        async (input: { text?: string; voice?: string }, runnable) => {
          const run = runnable as RunnableConfig | undefined;
          const speech = getMediaConfig(req.config)?.speech;
          const words = String(input.text ?? '').trim();
          if (speech && words.length > speech.maxChars) {
            return text(
              `The text is too long to speak in one file (${words.length} characters, at most ${speech.maxChars}). Ask the user to shorten it, or split it into parts.`,
            );
          }
          if (words === '') {
            return text('There is no text to speak.');
          }
          return guarded(
            (config) => config.speech != null,
            {
              model: speech?.model ?? '',
              endpoint: getMediaConfig(req.config)?.endpoint ?? '',
              context: MEDIA_TRANSACTION_CONTEXTS.speech,
              conversationId: run?.configurable?.thread_id,
            },
            speech?.estimateUsd ?? 0,
            multiplierOf(),
            async (config) => {
              const settings = config.speech!;
              const endpoint = endpointOf(config);
              const voices = [settings.voice, ...(settings.voices ?? [])];
              const voice =
                input.voice && voices.includes(input.voice) ? input.voice : settings.voice;
              const target = {
                ...endpoint,
                route: 'public' as const,
                endpoint: endpoint.name,
                model: settings.model,
              };
              const signal = run?.signal;
              let synthesized;
              try {
                synthesized = await speechClient.synthesize({
                  target,
                  input: words,
                  voice,
                  ...(settings.instructions ? { instructions: settings.instructions } : {}),
                  responseFormat: settings.format,
                  timeoutMs: settings.timeoutMs,
                  signal,
                });
              } catch {
                throw new MediaError(
                  signal?.aborted ? 'aborted' : 'provider_error',
                  'Speech failed',
                );
              }
              if (synthesized.audio.length === 0) {
                throw new MediaError('no_output', 'No audio came back');
              }
              const costUsd = synthesized.generationId
                ? await speechClient.getGenerationCost({
                    target,
                    generationId: synthesized.generationId,
                  })
                : undefined;
              const wav = settings.format === 'pcm';
              const saved = await deps.saveMedia(req, {
                buffer: wav
                  ? pcmToWav(synthesized.audio, settings.pcmSampleRate)
                  : synthesized.audio,
                type: wav ? 'audio/wav' : 'audio/mpeg',
                filename: wav ? 'speech.wav' : 'speech.mp3',
                context: MEDIA_TRANSACTION_CONTEXTS.speech,
              });
              return {
                result: text(
                  `The audio is ready (file_id: ${saved.file_id}). Put this markdown in your reply exactly as written so it plays in the chat: ${mediaLink(saved, '🔊 audio')}`,
                ),
                costUsd,
              };
            },
          );
        },
        { ...mediaToolDefinitions[MediaTools.speech] } as never,
      ) as unknown as StructuredToolInterface,

    [MediaTools.higgsfield]: () =>
      tool(
        async (
          input: {
            model?: string;
            prompt?: string;
            aspect_ratio?: string;
            duration_seconds?: number;
            resolution?: string;
          },
          runnable,
        ) => {
          const run = runnable as RunnableConfig | undefined;
          const higgsfield = getMediaConfig(req.config)?.higgsfield;
          const model = higgsfield?.models.find((item) => item.id === input.model);
          if (higgsfield && !model) {
            return text(
              `Unknown Higgsfield model. Use one of: ${higgsfield.models.map((item) => item.id).join(', ')}.`,
            );
          }
          return guarded(
            (config) => config.higgsfield != null,
            {
              model: model?.id ?? '',
              endpoint: 'Higgsfield',
              context: MEDIA_TRANSACTION_CONTEXTS.higgsfield,
              conversationId: run?.configurable?.thread_id,
            },
            model?.priceUsd ?? 0,
            1,
            async (config) => {
              const settings = config.higgsfield!;
              const body: Record<string, unknown> = { prompt: String(input.prompt ?? '') };
              if (input.aspect_ratio) {
                body.aspect_ratio = input.aspect_ratio;
              }
              if (input.resolution) {
                body.resolution = input.resolution;
              }
              if (model!.kind === 'video' && input.duration_seconds) {
                body.duration = Math.round(Number(input.duration_seconds));
              }
              const output = await generateHiggsfield(doFetch, settings, {
                model: model!,
                input: body,
                idempotencyKey: randomUUID(),
                pollIntervalMs: settings.pollIntervalMs,
                timeoutMs: settings.timeoutMs,
                signal: run?.signal,
              });
              if (model!.kind === 'image') {
                return {
                  result: imageResult(output, `The image was generated with ${model!.label}.`),
                  costUsd: model!.priceUsd,
                };
              }
              const saved = await deps.saveMedia(req, {
                buffer: output.buffer,
                type: output.type,
                filename: `higgsfield.${extensionOf(output.type)}`,
                context: MEDIA_TRANSACTION_CONTEXTS.higgsfield,
              });
              return {
                result: text(
                  `The ${model!.label} video is ready (file_id: ${saved.file_id}). Put this markdown in your reply exactly as written so it plays in the chat: ${mediaLink(saved, '🎬 video')}`,
                ),
                costUsd: model!.priceUsd,
              };
            },
          );
        },
        { ...mediaToolDefinitions[MediaTools.higgsfield] } as never,
      ) as unknown as StructuredToolInterface,
  };

  return toolNames
    .filter((name): name is MediaTools => name in builders)
    .map((name) => builders[name as MediaTools]());
}
